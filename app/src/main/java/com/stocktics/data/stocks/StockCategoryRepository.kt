    fun getTopStocks(
        category: StockCategory,
        limit: Int = 5,
        isIndian: Boolean? = null
    ): List<CategoryStockItem> {
        val filtered = allCategoryStocks.filter { stock ->
            stock.category == category && (isIndian == null || stock.isIndian == isIndian)
        }
        return filtered.take(limit)
    }

    fun getAllStocks(
        category: StockCategory,
        isIndian: Boolean? = null,
        query: String = ""
    ): List<CategoryStockItem> {
        val q = query.trim().lowercase()
        return allCategoryStocks.filter { stock ->
            stock.category == category &&
                    (isIndian == null || stock.isIndian == isIndian) &&
                    (q.isEmpty() || stock.symbol.lowercase().contains(q) || stock.name.lowercase().contains(q))
        }
    }

    fun getCategoryTotalCount(category: StockCategory, isIndian: Boolean? = null): Int {
        return allCategoryStocks.count {
            it.category == category && (isIndian == null || it.isIndian == isIndian)
        }
    }

    /**
     * Enriches CategoryStockItem with live price and real, dynamic 52W High / Low metrics
     * fetched directly from Yahoo Finance API.
     */
    suspend fun enrichWithLiveQuotes(items: List<CategoryStockItem>): List<CategoryStockItem> = withContext(Dispatchers.IO) {
        items.map { item ->
            try {
                val enc = URLEncoder.encode(item.symbol, "UTF-8")
                val url = URL("https://query1.finance.yahoo.com/v8/finance/chart/$enc?interval=15m&range=1d")
                val conn = (url.openConnection() as HttpURLConnection).apply {
                    requestMethod = "GET"
                    connectTimeout = 3500
                    readTimeout = 3500
                    setRequestProperty("User-Agent", YahooFinanceClient.YAHOO_USER_AGENT)
                    setRequestProperty("Accept", "application/json")
                }
                if (conn.responseCode == 200) {
                    val text = conn.inputStream.bufferedReader().readText()
                    val json = JSONObject(text)
                    val resultArr = json.optJSONObject("chart")?.optJSONArray("result")
                    if (resultArr != null && resultArr.length() > 0) {
                        val meta = resultArr.getJSONObject(0).getJSONObject("meta")
                        val livePrice = meta.optDouble("regularMarketPrice", meta.optDouble("fulldayPrice", 0.0))
                        val live52Low = meta.optDouble("fiftyTwoWeekLow", 0.0)
                        val live52High = meta.optDouble("fiftyTwoWeekHigh", 0.0)
                        val rawChgPct = if (meta.has("regularMarketChangePercent")) meta.optDouble("regularMarketChangePercent") else if (meta.has("fulldayChangePercent")) meta.optDouble("fulldayChangePercent") else Double.NaN
                        val isPos = if (!rawChgPct.isNaN()) rawChgPct >= 0 else true
                        val chgStr = if (!rawChgPct.isNaN()) "${if (isPos) "+" else ""}${String.format(Locale.US, "%.2f%%", rawChgPct)}" else item.change

                        if (livePrice > 0.0) {
                            val currPrefix = if (item.isIndian) "₹" else "$"
                            val formattedPrice = "$currPrefix ${String.format(Locale.US, "%,.2f", livePrice)}"

                            var newMetricValue = item.metricValue
                            var newMetricHighlight = item.metricHighlight

                            when (item.category) {
                                StockCategory.FIFTY_TWO_WEEK_LOW -> {
                                    if (live52Low > 0.0) {
                                        val diff = ((livePrice - live52Low) / live52Low) * 100.0
                                        newMetricValue = "${if (diff >= 0) "+" else ""}${String.format(Locale.US, "%.1f%%", diff)}"
                                        newMetricHighlight = "52W L: $currPrefix ${String.format(Locale.US, "%,.2f", live52Low)}"
                                    }
                                }
                                StockCategory.FIFTY_TWO_WEEK_HIGH -> {
                                    if (live52High > 0.0) {
                                        val diff = ((livePrice - live52High) / live52High) * 100.0
                                        newMetricValue = "${if (diff >= 0) "+" else ""}${String.format(Locale.US, "%.1f%%", diff)}"
                                        newMetricHighlight = "52W H: $currPrefix ${String.format(Locale.US, "%,.2f", live52High)}"
                                    }
                                }
                                StockCategory.NEAR_SUPPORT -> {
                                    val supp = livePrice * 0.985
                                    newMetricHighlight = "Support: $currPrefix ${String.format(Locale.US, "%,.2f", supp)}"
                                }
                                StockCategory.NEAR_RESISTANCE -> {
                                    val res = livePrice * 1.015
                                    newMetricHighlight = "Resistance: $currPrefix ${String.format(Locale.US, "%,.2f", res)}"
                                }
                                else -> {
                                    // Retain fundamental Debt / Growth metrics
                                }
                            }

                            return@map item.copy(
                                price = formattedPrice,
                                rawPrice = livePrice,
                                change = chgStr,
                                isPositive = isPos,
                                metricValue = newMetricValue,
                                metricHighlight = newMetricHighlight
                            )
                        }
                    }
                }
                item
            } catch (_: Exception) {
                item
            }
        }
    }
